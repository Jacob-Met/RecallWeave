import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const out=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(out,'../../..');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const original=JSON.parse(await fs.readFile(path.join(out,'baseline/original-source-native.json'),'utf8'));
const name='courses/vector-geometry-explorer.html',entry=original.find(e=>e.path===name);
const produced=await fs.readFile(path.join(root,name));
await fs.writeFile(path.join(out,'original-suite-test-produced-vector.html'),produced);
const canonical=execFileSync('git',['-C',root,'show','3a3704c352f8a12e20c208445c2c5ade412b365d:'+name]);
const candidates=[canonical,Buffer.from(canonical.toString('utf8').replace(/\r?\n/g,'\r\n'))];
const before=candidates.find(bytes=>sha(bytes)===entry.native_sha256);
assert.ok(before,'Only restore exact known original native bytes');
await fs.writeFile(path.join(root,name),before);
for(const item of original)assert.equal(sha(await fs.readFile(path.join(root,item.path))),item.native_sha256,item.path);
const receipt={at:new Date().toISOString(),trigger:'Existing full-suite vector-geometry build test wrote its original generated file during native CRLF checkout parity failure.',path:name,testProducedSha256:sha(produced),restoredOriginalNativeSha256:sha(before),originalNativeLeavesPreserved:original.length,passed:true};
await fs.writeFile(path.join(out,'restored-test-effect.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify(receipt));
