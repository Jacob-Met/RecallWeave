import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {spawnSync,execFileSync} from 'node:child_process';
const root=path.dirname(new URL(import.meta.url).pathname);
const source=path.join(root,'source');
const out=path.join(root,'runtime/node-receiving');
fs.mkdirSync(out,{recursive:true});
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const head=execFileSync('/usr/bin/git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
assert.equal(head,'e00a98e5c19302e893600f6d45aac08b6a69a08d');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'SOURCE-MANIFEST.json')));
const owned=['courses/traceable-measurements.source.json','courses/traceable-measurements.json','courses/traceable-measurements.md','tools/build_traceable_measurements.mjs','tests/traceable-measurements-course.test.mjs','docs/receiving/traceable-measurements-9d2f71701d2e/measurement-report.json'];
const before=Object.fromEntries([...manifest.records.map(r=>r.path),...owned].map(p=>[p,hash(fs.readFileSync(path.join(source,p)))]));
const capacity=()=>{const s=fs.statfsSync(root);return s.bavail*s.bsize;};
const receipt={source_commit:head,canonical_learner:manifest.canonical_main,started_at:new Date().toISOString(),node:process.version,platform:process.platform,arch:process.arch,free_before_bytes:capacity(),runs:[],source_before:before};
assert.ok(receipt.free_before_bytes>=64*1024*1024,'64 MiB Node/source gate floor');
const run=(label,bin,args)=>{
 const start=Date.now();
 const r=spawnSync(bin,args,{cwd:source,encoding:'utf8',timeout:15000,maxBuffer:2*1024*1024,env:{...process.env,PYTHONDONTWRITEBYTECODE:'1'}});
 const log='$ '+[bin,...args].join(' ')+'\n'+(r.stdout||'')+(r.stderr||'')+'\n';
 fs.writeFileSync(path.join(out,label+'.log'),log,{flag:'wx'});
 const row={label,exit:r.status,signal:r.signal,error:r.error?.message??null,elapsed_ms:Date.now()-start,log_sha256:hash(log)};
 receipt.runs.push(row);
 fs.writeFileSync(path.join(out,'RUN.json'),JSON.stringify(receipt,null,2)+'\n');
 assert.equal(r.status,0,label+' failed; original output retained');
};
run('course-builder-check',process.execPath,['tools/build_traceable_measurements.mjs','--check']);
run('course-content-tests',process.execPath,['--test','tests/traceable-measurements-course.test.mjs']);
run('unchanged-demo-build','/Users/me/hamon-gait-event-figures-20261008-566d51f04b31/venv/bin/python',['tools/make_demo.py']);
for(const [p,sha] of Object.entries(before)) assert.equal(hash(fs.readFileSync(path.join(source,p))),sha,'Source changed: '+p);
receipt.ended_at=new Date().toISOString();
receipt.free_after_bytes=capacity();
receipt.protected_files_unchanged=Object.keys(before).length;
receipt.passed=true;
fs.writeFileSync(path.join(out,'RUN.json'),JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({source_commit:head,runs:receipt.runs,protected_files_unchanged:receipt.protected_files_unchanged,free_after_bytes:receipt.free_after_bytes,passed:true}));
