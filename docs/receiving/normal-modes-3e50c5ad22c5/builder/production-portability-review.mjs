import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,join,relative} from 'node:path';
import {spawnSync} from 'node:child_process';
const [sourceArg,packetArg,workArg]=process.argv.slice(2);
assert.ok(sourceArg&&packetArg&&workArg,'Supply source root, packet, and fresh work root.');
const source=resolve(sourceArg),packet=resolve(packetArg),work=resolve(workArg);
await mkdir(work);
const moved=join(work,'renamed final packet'),caller=join(work,'foreign caller');
await cp(packet,moved,{recursive:true,force:false,errorOnExist:true});await mkdir(caller);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const entry=await readFile(join(moved,'production-review.mjs'),'utf8');
assert.doesNotMatch(entry,/(?:\/home\/jacob|\/workspace\/scratch|\/tmp\/hamon)/,'New receiver must not depend on a fixed host path.');
const result=spawnSync(process.execPath,[relative(caller,join(moved,'production-review.mjs')),relative(caller,source),'relocated-production'],{cwd:caller,encoding:'utf8',timeout:20000});
assert.equal(result.status,0,result.stderr+'\n'+result.stdout);
const replay=JSON.parse(result.stdout.trim());assert.equal(replay.pass,true);
const original=JSON.parse(await readFile(join(packet,'actual-production/production-receipt.json'),'utf8'));
assert.deepEqual(replay.sourceBefore,original.sourceBefore);
assert.equal(replay.results[0].sha256,original.results[0].sha256);
assert.deepEqual(replay.results.map(item=>[item.name,item.pass]),original.results.map(item=>[item.name,item.pass]));
const receipt={completedAt:new Date().toISOString(),node:process.version,pass:true,receiverSHA256:hash(entry),relativeCliArguments:true,foreignWorkingDirectory:true,renamedPacketPathContainsSpaces:true,physicsNumericalSuitesExecuted:false,sourcePinsMatchOriginalRun:true,generatedHtmlMatchesOriginalRun:true,executedGroups:replay.results.length,originalRun:original.completedAt,replay};
await writeFile(join(work,'production-portability-receipt.json'),JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({completedAt:receipt.completedAt,pass:true,receiverSHA256:receipt.receiverSHA256,relativeCliArguments:true,foreignWorkingDirectory:true,renamedPacketPathContainsSpaces:true,executedGroups:receipt.executedGroups,physicsNumericalSuitesExecuted:false},null,2));
